import { P, REPOS, write } from './lib.mjs';

export function readme() {
  const V = '?v=1';                       // bump this when you republish an image so GitHub's cache refreshes
  const u = P.username;
  const img = (file, alt) => `<img src="assets/${file}${V}" alt="${alt}" width="100%">`;

  const rows = REPOS.map(r => {
    const stars = typeof r.stars === 'number' ? r.stars : '-';
    return `| [**${r.name}**](https://github.com/${u}/${r.name}) | ${r.desc} | ${r.lang} | ${stars} |`;
  }).join('\n');

  const posts = P.articles_list.map(a => `- [${a.title}](${a.url})`).join('\n');
  const links = P.links.map(l => `[${l.label}](${l.url})`).join(' · ');

  const md = `<!-- Generated by scripts/build.mjs. Edit data/*.json and re-run \`node scripts/build.mjs\`. -->
<div align="center">

${img('hero.svg', `${P.name} - ${P.roles[0]}`)}

${img('about-life.svg', 'About me and life outside the editor')}

${img('stack.svg', 'Tech stack orbiting a glowing core, plus a grouped chip grid')}

${img('id-dashboard.svg', 'Lanyard ID badge and stats dashboard')}

</div>

## Featured projects

| Project | What it does | Language | Stars |
| --- | --- | --- | --- |
${rows}

More on my [repositories tab](https://github.com/${u}?tab=repositories).

## Latest writing

${posts}

## Contributions, as a city at night

<div align="center">

<img src="profile-3d-contrib/profile-night-view.svg${V}" alt="3D contribution city, night view" width="100%">

</div>

<sub>Rebuilt every day by [github-profile-3d-contrib](https://github.com/yoshi389111/github-profile-3d-contrib).</sub>

## Connect

<div align="center">

${img('connect.svg', 'Links to my profiles')}

</div>

${links}
`;
  return write('README.md', md);
}
